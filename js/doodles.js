export const DOODLE_KEYS = Object.keys(DOODLES);

export function doodleKey(name) {
  for (const [re, key] of RULES) if (re.test(name)) return key;
  return null;
}

const line = (pts, dx) => `<polyline class="dd-body" points="${pts.map(([x, y]) => `${x + dx},${y}`).join(' ')}"/>`;

function panel(p, dx) {
  return `<g transform="translate(${dx} 0)">${p.props}${p.lines.map((l) => line(l, 0)).join('')}<circle class="dd-head" cx="${p.h[0]}" cy="${p.h[1]}" r="5"/></g>`;
}

export function doodleSvg(name) {
  const key = doodleKey(name);
  if (!key) return '';
  const [a, b] = DOODLES[key];
  return `<div class="doodle" aria-hidden="true"><svg viewBox="0 0 132 76" role="img">
    <path class="dd-ground" d="M2 69.5H64M68 69.5H130"/>
    ${panel(a, 2)}
    <path class="dd-arrow" d="M62 36h8m-3-3l3 3-3 3"/>
    ${panel(b, 70)}
  </svg><div class="doodle-cap"><span>início</span><span>fim</span></div></div>`;
}
